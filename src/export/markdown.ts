// Markdown export — spec §7 FR-12 (Build 5).
// Human-readable report: score with grade/coverage/confidence,
// categories, observations, key evidence with sources, and the
// limitations — never a bare number. A provisional report (coverage
// below the 40% minimum) exports "Not enough data" instead of a
// score, with the coverage that explains why.

import { gradeLabel } from '../analysis/scoring';
import type { ActivityData } from '../domain/activity';
import type { RepositoryReport } from '../domain/report';
import type { OverviewResult } from '../domain/repository';
import { buildCompareRows, type CompareEntry } from '../compare/compare';

function confidenceText(confidence: RepositoryReport['confidence']): string {
  return confidence === 'high' ? 'High' : confidence === 'medium' ? 'Medium' : 'Low';
}

function formatScore(report: RepositoryReport): string {
  if (report.provisional || report.overallScore === null) {
    return `Not enough data (coverage ${report.coverage}% — below the 40% minimum for a score)`;
  }
  const grade = report.grade === null ? '' : `, grade ${report.grade} (${gradeLabel(report.grade)})`;
  return `${report.overallScore} / 100${grade}`;
}

function observationsSection(report: RepositoryReport): string {
  const lines: string[] = [];
  if (report.observations.good.length > 0) {
    lines.push('### Good signs', '');
    for (const item of report.observations.good) lines.push(`- ${item}`);
    lines.push('');
  }
  if (report.observations.caution.length > 0) {
    lines.push('### Possible concerns', '');
    for (const item of report.observations.caution) lines.push(`- ${item}`);
    lines.push('');
  }
  if (report.observations.unknown.length > 0) {
    lines.push('### Could not be concluded', '');
    for (const item of report.observations.unknown) lines.push(`- ${item}`);
    lines.push('');
  }
  return lines.join('\n');
}

export function reportToMarkdown(
  overview: OverviewResult,
  report: RepositoryReport,
  activity: ActivityData,
): string {
  const facts = overview.facts;
  const lines: string[] = [
    `# RepoRadar report: ${facts.fullName}`,
    '',
    `Repository: [${facts.fullName}](${facts.htmlUrl})`,
    facts.description ? `Description: ${facts.description}` : 'Description: none',
    '',
    '## Health score',
    '',
    `**Score:** ${formatScore(report)}`,
    `**Coverage:** ${report.coverage}%`,
    `**Confidence:** ${confidenceText(report.confidence)}`,
    `**Score model:** ${report.scoreModelVersion}`,
    `**Generated:** ${report.generatedAt}`,
    `**Data fetched:** ${facts.fetchedAt}${overview.stale ? ' (stale cached data — the live request failed)' : ''}`,
    '',
    '## Categories',
    '',
    '| Category | Score | Status |',
    '| --- | --- | --- |',
  ];
  for (const category of report.categories) {
    const score = category.score === null ? 'Not enough data' : `${category.score} / 100`;
    lines.push(`| ${category.label} | ${score} | ${category.status} |`);
  }
  lines.push('', observationsSection(report));
  if (report.sampleNotes.length > 0) {
    lines.push('## Sampling notes', '');
    for (const note of report.sampleNotes) lines.push(`- ${note}`);
    lines.push('');
  }
  lines.push('## Key evidence', '');
  for (const item of report.evidence) {
    const value = item.value === null ? 'unknown' : String(item.value);
    const limitation = item.limitation ? ` — limitation: ${item.limitation}` : '';
    const window = item.window ? ` (window: ${item.window})` : '';
    lines.push(`- **${item.key}**: ${value} — source: ${item.source}, observed ${item.observedAt}${window}${limitation}`);
  }
  lines.push('');
  if (overview.languages && overview.languages.entries.length > 0) {
    lines.push('## Languages', '');
    for (const entry of overview.languages.entries) {
      lines.push(`- ${entry.name}: ${entry.percent}%`);
    }
    lines.push('');
  }
  const contributors = activity.contributors === null ? 'unknown' : String(activity.contributors.length);
  lines.push(
    '## Key metrics',
    '',
    `- Stars: ${facts.stars}`,
    `- Forks: ${facts.forks}`,
    `- Watchers: ${facts.watchers}`,
    `- Open issues (includes open pull requests): ${facts.openIssuesCount}`,
    `- Contributors (sample): ${contributors}`,
    `- Last push: ${facts.pushedAt ?? 'unknown'}`,
    '',
    '## Limitations',
    '',
    '- A score is an evidence-based heuristic, not proof of code quality, security, or safety.',
    '- GitHub counts open issues and open pull requests together in the open-issues field.',
    '- Activity figures are bounded samples (contributors, commits, issues and pull requests are capped at one page), not the full history.',
    '- Traffic, vulnerability and security-alert data are not available for arbitrary public repositories and are never inferred.',
    '',
    `Generated by RepoRadar, score model ${report.scoreModelVersion}, ${report.generatedAt}.`,
    '',
  );
  return lines.join('\n');
}

function formatCompareValue(rowKey: string, value: number | string | null): string {
  if (value === null) return '—';
  if (rowKey === 'coverage' || rowKey === 'issueClosure') return `${value}%`;
  return String(value);
}

export function compareToMarkdown(entries: CompareEntry[]): string {
  const rows = buildCompareRows(entries);
  const generatedAt = entries[0]?.report.generatedAt ?? new Date().toISOString();
  const modelVersion = entries[0]?.report.scoreModelVersion ?? 'unknown';
  const lines: string[] = [
    '# RepoRadar comparison',
    '',
    `Compared: ${entries.map((e) => e.overview.facts.fullName).join(', ')}`,
    `Score model: ${modelVersion}`,
    `Generated: ${generatedAt}`,
    '',
    '| Metric | ' + entries.map((e) => e.overview.facts.fullName).join(' | ') + ' |',
    '| --- |' + entries.map(() => ' --- |').join(''),
  ];
  for (const row of rows) {
    const cells = row.values.map((value, i) => {
      const text = formatCompareValue(row.key, value);
      return row.best[i] ? `${text} ★ Best` : text;
    });
    lines.push(`| ${row.label} | ${cells.join(' | ')} |`);
  }
  lines.push(
    '',
    '## How to read this',
    '',
    '- Every column uses the same metric definitions, so the numbers are directly comparable.',
    '- "★ Best" marks the best value in a row; a missing value ("—") can never be best.',
    '- A score is an evidence-based heuristic, not proof of code quality, security, or safety.',
    '- Coverage and confidence travel with each score — a higher score on thinner evidence is not automatically the better repository.',
    '',
    '## Coverage and confidence',
    '',
  );
  for (const entry of entries) {
    const score =
      entry.report.provisional || entry.report.overallScore === null
        ? 'Not enough data'
        : `${entry.report.overallScore} / 100 (grade ${entry.report.grade ?? '—'})`;
    lines.push(
      `- ${entry.overview.facts.fullName}: ${score}, coverage ${entry.report.coverage}%, confidence ${confidenceText(entry.report.confidence)}`,
    );
  }
  lines.push('', `Generated by RepoRadar, score model ${modelVersion}, ${generatedAt}.`, '');
  return lines.join('\n');
}
