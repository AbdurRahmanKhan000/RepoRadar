// Build 5: Markdown + JSON export output is exact for fixed
// fixture reports. A provisional report must export "Not enough
// data" instead of a number — never a bare score without its
// coverage and limitations.

import { describe, expect, it } from 'vitest';
import { buildReport } from '../../src/analysis/scoring';
import type { ActivityData } from '../../src/domain/activity';
import type { OverviewResult } from '../../src/domain/repository';
import { compareToMarkdown, reportToMarkdown } from '../../src/export/markdown';
import { buildReportExport, toReportJson } from '../../src/export/json';
import { activeRepo, archivedRepo, FIXED_NOW, makeActivity, makeFacts } from './scoring-fixtures';

function makeOverview(): OverviewResult {
  const { facts } = activeRepo();
  return {
    ref: { platform: 'github', host: 'github.com', owner: 'test', repo: 'repo' },
    facts,
    languages: {
      entries: [
        { name: 'TypeScript', bytes: 900, percent: 90 },
        { name: 'JavaScript', bytes: 100, percent: 10 },
      ],
      totalBytes: 1000,
      fetchedAt: new Date(FIXED_NOW).toISOString(),
    },
    languagesError: null,
    liveError: null,
    evidence: [],
    rateLimit: null,
    fromCache: false,
    stale: false,
    fetchedAt: new Date(FIXED_NOW).toISOString(),
  };
}

describe('reportToMarkdown — active repo', () => {
  it('contains score, grade, coverage, limitations and evidence sources', () => {
    const { facts, activity } = activeRepo();
    const report = buildReport(facts, activity, { nowMs: FIXED_NOW, evidence: [] });
    const overview = makeOverview();
    const md = reportToMarkdown(overview, report, activity);

    expect(md).toContain('# RepoRadar report: test/repo');
    expect(md).toContain('**Score:** 94.2 / 100, grade A');
    expect(md).toContain('**Coverage:** 100%');
    expect(md).toContain('**Confidence:** High');
    expect(md).toContain('**Score model:** 1.0.0');
    expect(md).toContain('| Maintenance |');
    expect(md).toContain('## Limitations');
    expect(md).toContain('not proof of code quality, security, or safety');
    // Evidence carries source endpoints.
    expect(md).toContain('GET /repos/{owner}/{repo}');
    expect(md).toContain('## Key evidence');
    // Key metrics and languages.
    expect(md).toContain('Stars: 250000');
    expect(md).toContain('TypeScript: 90%');
    expect(md).toContain(`Generated by RepoRadar, score model 1.0.0`);
  });

  it('JSON export carries the full report, facts, evidence and model version', () => {
    const { facts, activity } = activeRepo();
    const report = buildReport(facts, activity, { nowMs: FIXED_NOW, evidence: [] });
    const overview = makeOverview();
    const parsed = JSON.parse(toReportJson(overview, report, activity)) as ReturnType<
      typeof buildReportExport
    >;
    expect(parsed.exportedBy).toBe('RepoRadar');
    expect(parsed.scoreModelVersion).toBe('1.0.0');
    expect(parsed.repoId).toBe(report.repoId);
    expect(parsed.report.overallScore).toBe(94.2);
    expect(parsed.overview.facts.stars).toBe(250000);
    expect(parsed.overview.languages?.entries[0]?.name).toBe('TypeScript');
    expect(parsed.report.evidence.length).toBeGreaterThan(0);
    expect(parsed.limitations.join(' ')).toContain('not proof of code quality');
    // Pretty-printed: indented, multi-line.
    expect(toReportJson(overview, report, activity)).toContain('\n  "report":');
  });
});

describe('reportToMarkdown — provisional report', () => {
  it('exports "Not enough data" instead of a score number', () => {
    const facts = makeFacts({ stars: 10, forks: 2, pushedAt: null });
    const activity: ActivityData = {
      ...makeActivity(),
      contributors: null,
      commits: null,
      releases: null,
      issues: null,
      pulls: null,
      communityProfile: null,
      ciWorkflowsPresent: null,
    };
    const report = buildReport(facts, activity, { nowMs: FIXED_NOW, evidence: [] });
    expect(report.provisional).toBe(true);
    expect(report.overallScore).toBeNull();
    const md = reportToMarkdown(makeOverview(), report, activity);
    expect(md).toContain('Not enough data (coverage 10% — below the 40% minimum for a score)');
    expect(md).not.toContain('**Score:** null');
    expect(md).not.toMatch(/\*\*Score:\*\* \d/);
    // Coverage and the unknown observations still travel with it.
    expect(md).toContain('**Coverage:** 10%');
    expect(md).toContain('Could not be concluded');
  });
});

describe('compareToMarkdown', () => {
  it('tables the compared repos with best markers and coverage', () => {
    const entries = [activeRepo(), archivedRepo()].map(({ facts, activity }) => {
      const report = buildReport(facts, activity, { nowMs: FIXED_NOW, evidence: [] });
      const overview = makeOverview();
      return { repoId: report.repoId, overview: { ...overview, facts }, report, activity };
    });
    const md = compareToMarkdown(entries);
    expect(md).toContain('# RepoRadar comparison');
    expect(md).toContain('test/repo');
    expect(md).toContain('| Overall score | 94.2 ★ Best | 18.1 |');
    expect(md).toContain('coverage 100%');
    expect(md).toContain('A score is an evidence-based heuristic');
  });
});
